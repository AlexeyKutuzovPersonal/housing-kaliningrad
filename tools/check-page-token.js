// ============================================================
// check-page-token.js — принимает ли сервер ключ, зашитый в страницу.
//
//   node tools\check-page-token.js https://dom-kgd-2be42d1d18.pages.dev
//
// Проверяется НЕ «совпадает ли ключ с секретом», а то же самое, что
// делает браузер отца: берём ключ из самой живой страницы и идём с ним
// в /api/marks. Совпадение с секретом доказывает меньше — секрет может
// быть правильным, а в бою лежать страница прошлой сборки.
//
// Зачем вообще. Ключ страницы живёт в Rep\.sync-token и попадает в
// html генератором; серверный — в переменных проекта Pages. Это два
// разных места, и они разошлись 2026-08-23: ключ сменили на сервере, а
// страницу не пересобрали. Отказ при этом НЕ выглядит отказом —
// страница открывается, таблица на месте, разметка рисуется из
// localStorage. Молча ломается только запись. Разошлось на шесть
// недель, и нашлось не проверкой, а тем, что человек заметил пропажу
// чужих меток.
//
// Поэтому проверка стоит в двух местах: в хуке pre-push сразу после
// выкладки (ловит в ту же минуту) и в ночном Action (ловит ротацию
// ключа, сделанную мимо выкладки, за сутки).
//
// Выход: 0 — сервер ключ принял; 1 — не принял или страница не отдала
// ключ вовсе.
// ============================================================

'use strict';

const БАЗА = (process.argv[2] || '').replace(/\/+$/, '');
if (!БАЗА) {
  console.error('Укажите адрес страницы: node tools/check-page-token.js https://…');
  process.exit(2);
}

// Ключ лежит в странице единственным местом — в конфигурации слоя
// синхронизации, которую печатает review-table.js. Ищем именно её, а
// не «что-нибудь похожее на токен»: случайное совпадение дало бы
// зелёную проверку на сломанной странице.
function ключИзСтраницы(html) {
  const m = html.match(/var SYNC = (\{[^\n]*?\});/);
  if (!m) return null;
  try {
    const cfg = JSON.parse(m[1]);
    return cfg && cfg.token ? String(cfg.token) : null;
  } catch (e) {
    return null;
  }
}

async function main() {
  const стр = await fetch(БАЗА + '/', { headers: { 'cache-control': 'no-cache' } });
  if (!стр.ok) {
    console.error(`НЕ ПРОВЕРЕНО: страница ${БАЗА}/ ответила ${стр.status}`);
    process.exit(1);
  }
  const html = await стр.text();
  const ключ = ключИзСтраницы(html);
  if (!ключ) {
    console.error('НЕ ПРОВЕРЕНО: в странице нет конфигурации синхронизации (var SYNC).');
    console.error('  Либо страница собрана без --deploy, либо разметка слоя связи изменилась.');
    process.exit(1);
  }

  const отв = await fetch(БАЗА + '/api/marks?since=0', { headers: { 'x-sync-token': ключ } });
  if (отв.status === 200) {
    const j = await отв.json().catch(() => null);
    const меток = j && j.marks ? Object.keys(j.marks).length : 0;
    console.log(`Ключ страницы сервер принимает. Правка ${j ? j.rev : '?'}, меток ${меток}.`);
    process.exit(0);
  }

  // Ключ печатать нельзя — он и есть право записи. Печатаем хвост,
  // которого достаточно, чтобы сверить две стороны глазами.
  console.error(`РАСХОЖДЕНИЕ КЛЮЧА: сервер ответил ${отв.status} на ключ, зашитый в живую страницу.`);
  console.error(`  Ключ страницы оканчивается на …${ключ.slice(-6)} (длина ${ключ.length}).`);
  console.error('  Страница при этом выглядит исправной, а разметка никуда не доезжает.');
  console.error('  Чинить так: сверить Rep\\.sync-token с переменной SYNC_TOKEN проекта Pages,');
  console.error('  затем пересобрать страницу (node tools\\dashboard-houses.js) и выложить.');
  process.exit(1);
}

main().catch((e) => {
  console.error('НЕ ПРОВЕРЕНО: ' + e.message);
  process.exit(1);
});
