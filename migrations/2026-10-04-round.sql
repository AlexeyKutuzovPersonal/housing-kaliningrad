-- Добавляет раунд просмотра (1..3) к уже существующей разметке.
--
-- ТОЛЬКО ADD COLUMN. Ни одна существующая строка marks/marks_log не
-- трогается: новый столбец у них становится NULL («раунд не назначен»),
-- ровно то же самое, что «этот объект ещё не распределили» для строк,
-- размеченных после миграции. schema.sql для НОВОЙ базы уже содержит
-- round изначально — этот файл только для БОЕВОЙ базы, где строки
-- (295 отметок и 250 заметок на 2026-10-04) уже есть и их нельзя
-- потерять.
--
-- Порядок выкладки (см. README.md, раздел «Миграции схемы D1»):
--   1. node tools\backup-marks.js --url https://dom-kgd-2be42d1d18.pages.dev/api/marks
--   2. cf.cmd d1 execute dom-kgd-marks --remote --file=migrations/2026-10-04-round.sql
--   3. сверить GET /api/marks?since=0 с бэкапом из шага 1 — число отметок,
--      их цвета, заметки и общий вид не должны измениться, round просто
--      добавится со значением NULL у всех
--   4. git push (pre-push хук выложит уже готовый код /api/marks и страницу)
--
-- Применять ПЕРЕД push: functions/api/marks.js после этой правки уже
-- ждёт колонку round, и без нового столбца в боевой базе GET/POST начнут
-- падать (SQLite ответит «no such column: round»), а с ним — но БЕЗ этой
-- миграции — обычный push молча остановит синхронизацию обоим, кто уже
-- открыл страницу.
--
-- Обратный порядок безопасен в одну сторону: ПРЕЖНИЙ код на базе с
-- лишней nullable-колонкой работает как раньше, колонки он перечисляет
-- явно. Поэтому между шагами 2 и 4 страница живёт нормально.
-- ============================================================

ALTER TABLE marks     ADD COLUMN round INTEGER;
ALTER TABLE marks_log ADD COLUMN round INTEGER;
